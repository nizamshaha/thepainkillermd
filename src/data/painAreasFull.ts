// Standard questionnaire template (reused across areas with variations)
function makeQuestions(areaSpecific: { duration?: boolean; radiation?: boolean; character?: boolean }) {
  const qs: PainArea["questionnaire"]["questions"] = [];

  if (areaSpecific.duration !== false) {
    qs.push({
      id: "duration", text: "How long have you had this pain?", type: "single",
      options: [
        { id: "d1", label: "Less than 1 week", value: "less-than-1-week" },
        { id: "d2", label: "1–4 weeks", value: "1-4-weeks" },
        { id: "d3", label: "1–3 months", value: "1-3-months" },
        { id: "d4", label: "More than 3 months", value: "more-than-3-months" },
        { id: "d5", label: "Comes and goes", value: "comes-and-goes" },
      ],
    });
  }

  if (areaSpecific.character !== false) {
    qs.push({
      id: "character", text: "What does the pain feel like?", type: "single",
      options: [
        { id: "c1", label: "Aching", value: "aching" },
        { id: "c2", label: "Sharp or stabbing", value: "sharp" },
        { id: "c3", label: "Burning", value: "burning" },
        { id: "c4", label: "Shooting", value: "shooting" },
        { id: "c5", label: "Electric / tingling", value: "electric" },
        { id: "c6", label: "Stiff / tight", value: "stiff" },
      ],
    });
  }

  if (areaSpecific.radiation) {
    qs.push({
      id: "radiation", text: "Does the pain travel or spread to other areas?", type: "single",
      options: [
        { id: "ra1", label: "Stays in one area", value: "local" },
        { id: "ra2", label: "Travels to another area", value: "travels" },
      ],
    });
    qs.push({
      id: "radiationDetail", text: "Where does it travel to?", type: "single",
      condition: (a) => (a as Record<string, unknown>).radiation === "travels",
      options: [
        { id: "rd1", label: "Above the area", value: "above" },
        { id: "rd2", label: "Below the area", value: "below" },
        { id: "rd3", label: "To the other side", value: "other-side" },
      ],
    });
  }

  qs.push({
    id: "worse", text: "What makes it worse?", type: "multiple",
    options: [
      { id: "w1", label: "Movement / activity", value: "movement" },
      { id: "w2", label: "Rest / inactivity", value: "rest" },
      { id: "w3", label: "Specific positions", value: "positions" },
      { id: "w4", label: "Touch or pressure", value: "touch" },
      { id: "w5", label: "Nothing specific", value: "nothing" },
    ],
  });

  qs.push({
    id: "sensory", text: "Do you also have any of these?", type: "multiple",
    options: [
      { id: "se1", label: "Numbness", value: "numbness" },
      { id: "se2", label: "Tingling", value: "tingling" },
      { id: "se3", label: "Weakness", value: "weakness" },
      { id: "se4", label: "Swelling", value: "swelling" },
      { id: "se5", label: "None", value: "none" },
    ],
  });

  qs.push({
    id: "redflags", text: "Do you have any of these warning signs?", type: "multiple",
    options: [
      { id: "rf1", label: "New or worsening weakness", value: "weakness", triggersRedFlag: true },
      { id: "rf2", label: "Loss of bladder or bowel control", value: "bladder-bowel", triggersRedFlag: true },
      { id: "rf3", label: "Major trauma", value: "trauma", triggersRedFlag: true },
      { id: "rf4", label: "Fever with pain", value: "fever", triggersRedFlag: true },
      { id: "rf5", label: "Unexplained weight loss", value: "weight-loss", triggersRedFlag: true },
      { id: "rf6", label: "None of these", value: "none" },
    ],
  });

  qs.push({
    id: "previousTreatment", text: "Have you tried any treatment for this pain before?", type: "multiple",
    options: [
      { id: "pt1", label: "Painkillers / tablets", value: "medication" },
      { id: "pt2", label: "Physiotherapy", value: "physiotherapy" },
      { id: "pt3", label: "Hot / cold packs", value: "hot-cold" },
      { id: "pt4", label: "Massage or manual therapy", value: "massage" },
      { id: "pt5", label: "Injections", value: "injections" },
      { id: "pt6", label: "Surgery", value: "surgery" },
      { id: "pt7", label: "No previous treatment", value: "none" },
    ],
  });

  qs.push({
    id: "medications", text: "Are you currently taking any medication for this pain?", type: "single",
    options: [
      { id: "m1", label: "No medication", value: "none" },
      { id: "m2", label: "Over-the-counter painkillers (e.g., Paracetamol, Ibuprofen)", value: "otc" },
      { id: "m3", label: "Prescribed pain medication", value: "prescribed" },
      { id: "m4", label: "Other medication (please mention in notes)", value: "other" },
    ],
  });

  qs.push({ id: "intensity", text: "On a scale of 0–10, how intense is your pain most of the time?", type: "scale" });

  return qs;
}

function mkArea(p: Omit<PainArea, "questionnaire"> & { questionnaire?: PainArea["questionnaire"] }): PainArea {
  return { ...p, questionnaire: p.questionnaire || { questions: makeQuestions({ radiation: true }) } };
}

